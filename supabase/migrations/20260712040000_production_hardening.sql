CREATE TABLE IF NOT EXISTS public.activity_awards (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  event_key TEXT NOT NULL,
  activity_type TEXT NOT NULL,
  xp_earned INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, event_key)
);

ALTER TABLE public.activity_awards ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users read own activity awards" ON public.activity_awards
  FOR SELECT USING (auth.uid() = user_id);

CREATE TABLE IF NOT EXISTS public.ai_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  feature TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.ai_usage ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS idx_ai_usage_user_created ON public.ai_usage(user_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.consume_ai_quota(p_feature TEXT, p_limit INTEGER DEFAULT 10)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE used INTEGER;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  SELECT count(*) INTO used FROM public.ai_usage
    WHERE user_id = auth.uid() AND created_at > now() - interval '1 minute';
  IF used >= least(greatest(p_limit, 1), 30) THEN RETURN FALSE; END IF;
  INSERT INTO public.ai_usage(user_id, feature) VALUES(auth.uid(), left(p_feature, 40));
  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.award_activity(p_event_key TEXT, p_activity_type TEXT)
RETURNS TABLE(xp_points INTEGER, daily_streak INTEGER)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE award INTEGER;
DECLARE today_count INTEGER;
DECLARE daily_cap INTEGER;
DECLARE duration INTEGER;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  award := CASE p_activity_type
    WHEN 'tutor_message' THEN 10 WHEN 'mock_test' THEN 30
    WHEN 'writing_evaluation' THEN 50 WHEN 'speaking_evaluation' THEN 60
    WHEN 'daily_task' THEN 15 WHEN 'reading_practice' THEN 40 ELSE 0 END;
  IF award = 0 THEN RAISE EXCEPTION 'Unsupported activity'; END IF;
  duration := CASE p_activity_type
    WHEN 'tutor_message' THEN 5 WHEN 'mock_test' THEN 8 WHEN 'writing_evaluation' THEN 40
    WHEN 'speaking_evaluation' THEN 5 WHEN 'daily_task' THEN 15
    WHEN 'reading_practice' THEN 20 ELSE 0 END;
  daily_cap := CASE p_activity_type WHEN 'tutor_message' THEN 20 WHEN 'mock_test' THEN 3 ELSE 10 END;
  SELECT count(*) INTO today_count FROM public.activity_awards
    WHERE user_id = auth.uid() AND activity_type = p_activity_type
      AND created_at >= date_trunc('day', now());
  IF today_count >= daily_cap THEN
    RETURN QUERY SELECT p.xp_points, p.daily_streak FROM public.profiles p WHERE p.id = auth.uid();
    RETURN;
  END IF;

  INSERT INTO public.activity_awards(user_id, event_key, activity_type, xp_earned)
    VALUES(auth.uid(), left(p_event_key, 100), p_activity_type, award)
    ON CONFLICT (user_id, event_key) DO NOTHING;
  IF FOUND THEN
    INSERT INTO public.study_sessions(user_id, duration_minutes, activity_type, xp_earned)
      VALUES(auth.uid(), duration, p_activity_type, award);
    UPDATE public.profiles SET xp_points = profiles.xp_points + award,
      last_active_at = now(), updated_at = now() WHERE id = auth.uid();
  END IF;
  RETURN QUERY SELECT p.xp_points, p.daily_streak FROM public.profiles p WHERE p.id = auth.uid();
END;
$$;

REVOKE ALL ON FUNCTION public.consume_ai_quota(TEXT, INTEGER) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.award_activity(TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.consume_ai_quota(TEXT, INTEGER) TO authenticated;
GRANT EXECUTE ON FUNCTION public.award_activity(TEXT, TEXT) TO authenticated;
